#!/usr/bin/env python3
"""Generate Unicode ID_Start / ID_Continue range tables.

Usage:
    python tools/gen_unicode_id_tables.py <DerivedCoreProperties.txt> \
        src/private/unicode/UnicodeTables.inc

The input is the Unicode Character Database file:
    https://www.unicode.org/Public/15.1.0/ucd/DerivedCoreProperties.txt

ECMAScript uses ID_Start / ID_Continue (not XID_*). The generated table is
pinned to the Unicode version of the input file; update the file and rerun
when upgrading.
"""

import sys


def parse_properties(path):
    props = {"ID_Start": [], "ID_Continue": []}
    with open(path, encoding="utf-8") as source:
        for raw in source:
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            fields = [part.strip() for part in line.split(";")]
            if len(fields) < 2 or fields[1] not in props:
                continue
            span = fields[0]
            if ".." in span:
                first, last = span.split("..")
            else:
                first = last = span
            props[fields[1]].append((int(first, 16), int(last, 16)))

    for name, ranges in props.items():
        ranges.sort()
        merged = []
        for first, last in ranges:
            if merged and first <= merged[-1][1] + 1:
                merged[-1] = (merged[-1][0], max(merged[-1][1], last))
            else:
                merged.append((first, last))
        props[name] = merged
    return props


def emit(name, ranges, out):
    out.write(f"constexpr CodePointRange {name}[] = {{\n")
    for first, last in ranges:
        out.write(f"    {{0x{first:04X}u, 0x{last:04X}u}},\n")
    out.write("};\n\n")


def main():
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 1
    props = parse_properties(sys.argv[1])
    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by tools/gen_unicode_id_tables.py. Do not edit.\n")
        out.write("// Source: Unicode 15.1.0 DerivedCoreProperties.txt\n")
        out.write("// ECMAScript IdentifierStart/Part use ID_Start/ID_Continue.\n\n")
        emit("kIdStartRanges", props["ID_Start"], out)
        emit("kIdContinueRanges", props["ID_Continue"], out)
    print(
        f"ID_Start ranges: {len(props['ID_Start'])}, "
        f"ID_Continue ranges: {len(props['ID_Continue'])}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
